package paquete1;

public class Fantasma {
	private int fantasma_x;
	private int fantasma_y;
	
	public Fantasma () {
		this.fantasma_x = 10;
		this.fantasma_y = 10;
	}

	public int getFantasma_x() {
		return fantasma_x;
	}

	public void setFantasma_x(int fantasma_x) {
		this.fantasma_x = fantasma_x;
	}

	public int getFantasma_y() {
		return fantasma_y;
	}

	public void setFantasma_y(int fantasma_y) {
		this.fantasma_y = fantasma_y;
	}
	
}

