public class Comecocos {
	private int pac_x;
	private int pac_y;
	
	public Comecocos () {
		this.pac_x = 1;
		this.pac_y = 1;
	}

	public int getPac_x() {
		return pac_x;
	}

	public void setPac_x(int pac_x) {
		this.pac_x = pac_x;
	}

	public int getPac_y() {
		return pac_y;
	}

	public void setPac_y(int pac_y) {
		this.pac_y = pac_y;
	}
	
}
